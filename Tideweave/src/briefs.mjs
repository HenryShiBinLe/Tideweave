// Player-facing copy is separate from the technical chapter metadata.
export function beginnerBrief(l) {
  const name = i => l.nodes[i]?.label ?? '起点';
  const count = l.nodes.length;
  let goal, controls, rules, insight;
  let hints = l.hints, perfect = l.perfect;
  switch (l.type) {
    case 'reach':
      goal = `标出从${name(l.source)}沿线能到达的所有设施，包括${name(l.source)}`;
      controls = `点击你认为能到达的设施，把它标亮；再点一次可取消。也要选中${name(l.source)}，全部选好后点击“运行检查”。`;
      rules = ['只看线路是否接通，画面上的距离不算。', `从${name(l.source)}出发，可以经过其他设施；没有设施的交叉处不接通。`];
      insight = '能沿一条或多条线路到达，就叫“可达”。没有直接连线，也可能通过别处到达。';
      break;
    case 'groups':
    case 'scc': {
      const directed = l.type === 'scc';
      goal = directed ? '沿箭头能互相往返的设施涂同色，其余分开' : '沿线能互相到达的设施涂同色，其余分开';
      controls = '先在色样中选一种颜色，再点击设施分组。相通的一整组用同一种颜色，不同组换颜色；再次点击同色设施可取消标记。';
      rules = [directed ? '必须既能去、又能回；可以经过同组其他设施。' : '可以经过同组其他设施，不必直接相连。',
        '能互相到达的设施不能拆成两组；不能到达的设施不能混为一组。'];
      insight = directed ? '能互相往返的最大一组，叫“强连通分量”。只有去路、没有回路的两组不能合并。' : '互相能到达的一整组，叫“连通分量”；独立设施也自成一组。';
      break;
    }
    case 'dfs':
      goal = l.strict ? `从${name(l.source)}巡检全部设施：有没去过的邻站先去，没有就按来路退一站` : `从${name(l.source)}出发，把 ${count} 个设施都走到`;
      controls = `你已经在${name(l.source)}。点击与当前位置直接相连的设施前进；要沿原路返回，也要点击上一站。“撤销”只修改计划，不算走回去。`;
      rules = ['可以重复经过设施和线路；不要求最终回到起点。',
        l.strict ? '还有没去过的相邻设施时，不能提前返回；没有时，只能返回来路的上一站。' : '没有新路时沿来路返回，再找没走过的支路。', '撤销用于改计划，不算实际走回去。'];
      insight = '先走到底，再沿来路退回找漏掉的支路，叫“深度优先搜索”。返回也是探索的一部分。';
      break;
    case 'broadcast':
      goal = l.fixedSource ? `填出${name(l.target)}第几轮收到信号` : `选发射站并填准确轮数，让所有设施在 ${l.limit} 轮内收到信号`;
      controls = l.fixedSource ? `用下方 − / + 填写${name(l.target)}收到信号的轮数。发射站在第 0 轮已有信号；每过一轮，信号向外传一条线。` : '先点击设施选择发射站，再用 − / + 填写最后一座站收到信号的轮数。发射站算第 0 轮，每轮向外传一条线。';
      rules = ['发射站在第 0 轮已有信号；它旁边的设施在第 1 轮收到。', '同一轮可以向多条线路传播；刚收到的设施下一轮才能继续转发。', l.fixedSource ? `只填写${name(l.target)}的到达轮数。` : '填写最后一个设施收到信号时的轮数，不是所有轮数相加。'];
      insight = '一圈一圈扩散，叫“广度优先搜索”；第一次收到信号的轮数，就是到起点的最少线路数。';
      break;
    case 'forest':
      goal = '选出保留的线路，让原本相通的设施仍能互相到达';
      controls = '点击要保留的线路，选中后会变亮；再点一次可取消。检查时只保留亮起的线路，灰线会被移除。';
      hints = ['先检查有没有设施被单独留下。', '两处设施之间若有两条走法，试着去掉其中一条线路。', '每片网络有几个设施，就尝试只留比这个数少 1 的线路。'];
      rules = ['只使用选中的线路；原来分开的网络不必互相接通。', '先保证原有连接不丢失，再尝试减少线路。'];
      insight = '同一片网络连起来又不绕成圈，叫“生成树”；多片这样的网络组成“森林”。';
      break;
    case 'euler':
      goal = `从${name(l.source)}出发，每条线路都走一遍，不能重复`;
      controls = `你已经在${name(l.source)}。依次点击有线相连的下一站，画出整条巡运路线；同一个设施可以再次经过，但线路不能重复走。`;
      rules = ['每条线路恰好走一次，但同一个设施可以经过多次。', '不要求回到起点；起点已由本关指定。'];
      insight = '每条线路恰好走一次，叫“欧拉路径”。连接 1、3、5…条线路的站叫“奇度点”；途中进出要成对，所以只能有 0 或 2 个这样的站。';
      break;
    case 'shortest':
    case 'routes':
      goal = l.type === 'routes' ? `分别从${name(l.source)}送到${l.targets.map(name).join('、')}，总用时不超过 ${l.budget}` : `从${name(l.source)}送到${name(l.target)}，用时不超过 ${l.budget}`;
      controls = l.type === 'routes' ? `先在下方选择一份运单，再从${name(l.source)}依次点击相连的下一站。每份运单都要单独规划；线路数字是耗时，各份用时相加。` : `你已经在${name(l.source)}。依次点击与当前位置直接相连的下一站，直到目的地。线路数字是耗时，经过的数字相加就是总用时。`;
      rules = ['用时按经过的线路数字相加，不按画面上的线长。',
        l.type === 'routes' ? `每份运单都从${name(l.source)}重新出发，各份用时相加。` : `最后一步必须到达${name(l.target)}。`, '先送达并满足时限，再尝试更快的路线。'];
      insight = '总用时最小的完整路线，叫“最短路”。眼前的一段便宜，不代表最后更快。';
      break;
    case 'floyd':
      goal = `新开放${name(l.stage)}中转，选出全部用时变短的两站组合`;
      controls = `比较新增${name(l.stage)}中转前后的用时，点击变快的两站组合，再点可取消。组合上的数字是原用时；∞ 表示原来不通，从不通变为可达也要选。`;
      rules = [`现在可经${l.nodes.slice(0,l.stage+1).map(n=>n.label).join('、')}中转；其他站只能作起终点。`, '组合中的数字是本轮开放前的最短用时；∞ 表示原来无法到达。更快或从不通变为可达才选，相等不选。', '例如：原用时 9，两段中转用时 2 + 3 = 5，这一对就变短了。'];
      insight = '每次多允许一个中转站，再更新站点之间的距离，叫“Floyd 算法”；不是挑一个最好的站。';
      break;
    case 'postman':
      goal = `从${name(l.source)}出发，走过全部线路，再回到${name(l.source)}`;
      controls = `你已经在${name(l.source)}。依次点击相连的下一站，走过全部线路后回到出发点。可以重复走；线路数字是里程，重复经过也会累加。`;
      rules = ['所有线路至少经过一次；必须回到起点。', '重复走也会增加里程，但不会直接判错。'];
      hints = ['数一数每个站连着几条线路。', '连着 1、3、5…条线路的站，进出不能全部配成对，需要补走。', '试着把这些站两两连起来补走；比较所有补走路线的总里程。'];
      insight = '连接奇数条线路的站叫“奇度点”。补走路线让它们进出成对；要比较全部配对的总里程，不能只挑最近的一对。';
      break;
    case 'mst':
      goal = `选线路接通全部 ${count} 个设施，总造价不超过 ${l.budget}`;
      controls = '点击线路或它的数字来选建，亮起表示已选；再点可取消。数字是这条线的造价，所有已选线路的造价相加。设施之间可以经过其他设施接通。';
      rules = ['只使用选中的线路；任意两处设施都要能沿它们互相到达。', '总造价是选中线路数字之和，不需要把图上所有线路都选上。', '不限制选线顺序；不同的低造价方案都可以通过。'];
      hints = ['先确认有没有设施还没有接上。', '两端已通过其他线路相通时，这条线可能可以省下。', '试着取消一条线路：若仍然全部相通，就不需要花这笔造价。'];
      perfect = l.id === '03-02.2' ? '总造价 8' : l.perfect;
      insight = '以最低总造价接通所有设施，得到“最小生成树”。不要的线路可以不建，最佳方案也可能不止一种。';
      break;
    case 'topo':
      goal = `排好 ${count} 项任务：箭头前的做完，后面的才能开始`;
      controls = '按你希望开工的先后顺序点击任务。箭头 A → B 表示 A 必须先于 B；多个箭头指向同一任务时，前面的都要先完成。再点已排任务，会从那里撤回。';
      rules = ['A → B 表示 A 做完后才能做 B，不是道路。', '有多个前置任务时，要等它们全部完成。', '没有先后要求的任务可以交换顺序。'];
      insight = '把所有前置任务放在后续任务之前，叫“拓扑排序”。互不依赖的任务可以换顺序。';
      break;
    case 'cycle':
      goal = '找一圈互相等待的任务，沿箭头走回起点';
      controls = '点击一个任务作为起点，再沿箭头依次点击后续任务。最后再次点击起点，闭合这条循环；中间不要重复任务。“撤销”可退回一步。';
      rules = ['A → B 表示 B 必须等 A 完成；箭头不是可双向走的路。', '选出的顺序要闭合，中间不能重复任务。', '只找真正围成一圈的任务，不要把圈外等候的任务也算进去。'];
      insight = '一圈任务互相等着对方先做，叫“有向环”；圈外等待的任务不一定属于环。';
      break;
    case 'schedule':
      goal = `最多用 ${l.budget} 份加速，让全部任务在 ${l.deadline} 天内完成`;
      controls = '每点一次任务，就用 1 份加速让它少做 1 天。减到只需 1 天后，再点会恢复原工期；“撤销”可退一步。不同支线可同时施工，施工时间线会随方案更新。';
      rules = ['每减少 1 天用 1 份加速，单项任务至少需要 1 天。', '箭头前的任务完成后，后面的才能开始；不同支线可以同时施工。', '没有工人数限制；总工期看最后一项何时完成，不把所有天数相加。'];
      insight = '决定最后完工时间的最长任务链，叫“关键路径”。同样长的链有两条时，只加速一条可能没用。';
      break;
    case 'color':
      goal = `给 ${count} 块区域上色，共用一段边界的不能同色`;
      controls = '先选一种色样，再点区域涂色；换色后点同一区域即可重涂。共用一段边界的区域不能同色，只在角上相碰可以同色。';
      rules = ['所有区域都要有颜色；共用一段边界的区域颜色必须不同。', '只在一个角相碰，不算相邻。', l.tutorial ? '本关只练习上色和分清边界，不要求减少颜色，也不参与徽记评分。' : '通关不限颜色数；达到挑战色数可获得徽记。'];
      hints = ['看区域有没有共用一段边界，不要只看位置近不近。', '沿围成一圈的区域试着轮流用两色，看看最后能否接上。', '若几块区域彼此都有共边，它们就要用不同颜色。'];
      insight = '把相邻关系转成“不能同色”，叫“图着色”。先满足相邻不同色，再研究能少用几种颜色。';
      break;
    case 'solid':
      goal = l.tutorial ? '给一个面上色，再打开展开图找到同一面' : `给全部 ${count} 个面上色，共用一条边的面不能同色`;
      controls = l.tutorial ? '先选色样并点击一个面上色，再点击“展开图”，确认同一个面的颜色被保留。拖动立体可旋转；这一关不要求涂满或减少色数。' : '先选色样，再点击面上色。按住鼠标拖动可旋转，隐藏面也要涂；也可切换“展开图”操作，两种视图的颜色同步。';
      rules = l.tutorial ? ['任意一个面涂色后，打开展开图即可检查通关，不需要涂满全部面。', '直接点面会着色，按住拖动只改变视角，不会涂色。', '找不到某个面时，可在面菜单中选它，再点击“着色”。'] : ['共享一条边的面不能同色，只碰到一个顶点不算。', '展开图上编号相同的两条边，折回去是同一条边；它们两侧的面仍然相邻。', '隐藏的面也要上色；可用面选择菜单定位，再点“着色”。颜色会在两种视图同步。'];
      insight = count === 6 ? '立方体相对的两个面不共边，可以同色；三组相对面最少用三色。' : '四面体每个面都和另外三个面共边，因此需要四色。';
      break;
    case 'matching':
      goal = `安排至少 ${l.coverage} 个岗位，一班一岗，不能重复占用`;
      controls = '左边是工班，右边是岗位。有线表示这个工班能做该岗位；点线安排，再点取消。一个工班只能接一岗，一个岗位也只能安排一班。';
      rules = ['左边是工班，右边是岗位；有线才表示该班能做这个岗位。', '每个工班最多做一个岗位，每个岗位最多用一个工班。', '可以先改派再检查，不会在改动中途判错。'];
      insight = '沿一串已选和未选的线调整岗位，有时能多安排一个人；这串改派路线叫“增广路径”。';
      break;
    case 'fault': {
      const object = l.faultKind === 'edge' ? '线路' : '设备';
      goal = `标出单独停用后，会让网络分成更多片的${object}`;
      controls = `先切到“停用测试”，点${object}观察哪些设施失去联系；再切回“标记”，点你认为关键的${object}作为答案。每次测试先恢复原图，测试本身不会选中答案。`;
      rules = ['每次只停用一个对象，下一次试验先恢复原图。', l.faultKind === 'edge' ? '停线只去掉这条线路，不关闭两端设备。' : '关设备时，它连着的线路一起停用。', '全部标记后点检查；不必按固定顺序测试。'];
      insight = l.faultKind === 'edge' ? '一停用就让网络分成更多片的线路，叫“桥”。' : '一关闭就让剩余网络分成更多片的设备，叫“割点”；线路都有替代路，也可能有这样的设备。';
      break;
    }
    case 'isolation':
      goal = `最多关闭 ${l.budget} 台设备，阻止故障从${name(l.source)}传到${name(l.target)}`;
      controls = `点击设备选择关闭，再点可取消。故障传播前会先关闭这些设备及关联线路；${name(l.source)}和${name(l.target)}不能关闭。选好后点击“运行检查”。`;
      rules = ['设备在故障开始前就关闭，它连着的线路一起停止传递。', '故障每轮沿线路传到旁边的设备；必须让保护目标一直安全。', '预算可以不用完；同样安全时，受影响设备越少越好。'];
      insight = '隔离要切断从故障起点到保护目标的所有通路；不是每次都关连接最多的设备。';
      break;
    case 'cut':
      goal = `停用线路，让${name(l.source)}无法沿线到达${name(l.target)}`;
      controls = '点击要停用的线路，再点可取消。注意：这次选中的是要断开的线；没有选中的线仍能通行。选好后点击“运行检查”。';
      rules = ['选中的是要停用的线路，其他线路仍然可用。', '断开指定两站就能通关；再尝试少停几条。'];
      insight = '让指定两站断开所需停用的最少线路集合，叫这两站之间的“最小割”。';
      break;
    case 'reinforce':
      goal = `加线造价不超过 ${l.budget}；任意${l.faultKind === 'edge' ? '一条线' : '一台设备'}坏了，其余仍能互通`;
      controls = '实线是已经建好的线路，不用选择。点击虚线或造价数字来新增线路，再点可取消。运行检查会分别模拟每一次单独故障，损坏不会累计。';
      rules = [`预算只计算新增虚线；检查时每次单独停用${l.faultKind === 'edge' ? '一条线路' : '一台设备和它的关联线路'}。`, '每次故障后，其余设施仍要能互相到达。', '不同故障分别测试，不会连续累计损坏。'];
      insight = '给线路准备绕行路，和给设备准备替代连接，是两种不同的加固目标。';
      break;
    default: throw new Error(`Missing beginner copy: ${l.type}`);
  }
  const optimizable = ['forest','mst','shortest','routes','postman','schedule','color','solid','matching','isolation','cut','reinforce'];
  const badge = !l.tutorial && (optimizable.includes(l.type) || l.type === 'broadcast' && !l.fixedSource) ? perfect : '';
  return {goal,controls,rules,rule:rules.join(' '),insight,hints,perfect,badge};
}
